export function useTextes() {
  const { langue } = useLangue();
  const dico: Record<string, string> = langue === "en" ? en : langue === "pcm" ? { ...en, ...pcm } : fr;
  const tx = (cle: CleTexte, variables?: Variables) => remplir(dico[cle] ?? fr[cle], variables);
  const dyn = (cle: string, variables?: Variables) => remplir(dico[cle] ?? (fr as Record<string, string>)[cle] ?? cle, variables);
  const fmt = langue === "fr" ? "fr" : "en";
  const xaf = (montant: string | bigint | number) => formatXaf(montant, fmt);
  const date = (iso: string | null | undefined) => formatDate(iso, fmt);
  return { langue, tx, dyn, xaf, date };
}

/** Montant entier XAF → « 25 000 FCFA » (aucun flottant). */
export function formatXaf(montant: string | bigint | number, langue: "fr" | "en" = "fr"): string {
  const s = String(montant).trim();
  const neg = s.startsWith("-");
  const digits = (neg ? s.slice(1) : s).replace(/\D/g, "") || "0";
  const sep = langue === "en" ? "," : " ";
  const groupes = digits.replace(/\B(?=(\d{3})+(?!\d))/g, sep);
  return `${neg ? "−" : ""}${groupes} FCFA`;
}

/** AAAA-MM-JJ (ou instant ISO) → date lisible, sans décalage de fuseau. */
export function formatDate(iso: string | null | undefined, langue: "fr" | "en" = "fr"): string {
  if (!iso) return "—";
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso);
  if (!m) return iso;
  const d = new Date(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3]), 12));
  return d.toLocaleDateString(langue === "en" ? "en-GB" : "fr-FR", { weekday: "short", day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });
}

/** Additionne des montants entiers en chaîne (BigInt, jamais de flottant). */
export function somme(montants: readonly string[]): string {
  return montants.reduce((acc, m) => acc + BigInt(/^-?\d+$/.test(m) ? m : "0"), 0n).toString();
}
