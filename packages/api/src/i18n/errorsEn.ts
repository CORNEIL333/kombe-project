/** Vrai si la langue préférée de la requête est l'anglais (`en`, `en-GB`…). */
export function prefersEnglish(acceptLanguage: unknown): boolean {
  if (typeof acceptLanguage !== "string") return false;
  const first = acceptLanguage.split(",")[0]?.split(";")[0]?.trim().toLowerCase() ?? "";
  return first === "en" || first.startsWith("en-");
}

/** Motif dans la langue demandée ; à défaut de traduction, le motif d'origine. */
export function localizeMessage(message: string, acceptLanguage: unknown): string {
  if (!prefersEnglish(acceptLanguage)) return message;
  const direct = ERRORS_EN[message];
  if (direct !== undefined) return direct;
  for (const [re, render] of PATTERNS) {
    const m = message.match(re);
    if (m) return render(m);
  }
  return message;
}
